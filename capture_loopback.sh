#!/usr/bin/env bash
# Capture a short trace from the local loopback interface only.
set -euo pipefail

OUT_DIR="captures"
DURATION="${1:-60}"
OUT_FILE="${2:-${OUT_DIR}/loopback-$(date +%Y%m%d-%H%M%S).pcap}"

if ! [[ "$DURATION" =~ ^[0-9]+$ ]] || (( DURATION < 1 || DURATION > 300 )); then
  echo "Duration must be an integer from 1 to 300 seconds."
  exit 2
fi

mkdir -p "$OUT_DIR"
echo "Capturing loopback traffic for up to ${DURATION}s."
echo "Output: ${OUT_FILE}"
echo "Only use this for traffic generated by you on this machine."

sudo timeout "$DURATION" tcpdump -i lo -nn -s 0 -w "$OUT_FILE"
echo "Capture complete. Review and sanitize before sharing."
